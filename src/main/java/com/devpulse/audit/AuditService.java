package com.devpulse.audit;

import jakarta.annotation.PostConstruct;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import javax.sql.DataSource;
import java.sql.Timestamp;
import java.time.Clock;
import java.time.Instant;
import java.util.List;

/**
 * A permanent record of "who did what". It exists mainly to demonstrate TRANSACTION PROPAGATION:
 * what should happen when a transactional method is called while another transaction is running?
 *
 *   recordWithinTransaction  -> MANDATORY
 *       Must be called inside an existing transaction and JOINS it. Called with no transaction,
 *       it throws. If the caller later rolls back, this audit row is rolled back too.
 *       Use when: "this row only makes sense together with the business change".
 *
 *   recordIndependently      -> REQUIRES_NEW
 *       Suspends the caller's transaction and runs in its OWN new one, committed immediately.
 *       If the caller later rolls back, this row SURVIVES.
 *       Use when: "I must keep a trace even if the main operation fails" (e.g. rejected attempts).
 *
 *   (default, REQUIRED, used by ProjectService.register)
 *       Join the current transaction if there is one, otherwise start one.
 *
 * IMPORTANT: @Transactional works through a PROXY Spring puts around this bean. It only applies
 * when another bean calls these methods. A method calling another method on `this` bypasses the
 * proxy, so annotations on the inner call are ignored. That is why ProjectService (a different
 * bean) calls this class instead of ProjectService calling its own methods.
 *
 * Schema: created here in @PostConstruct, which runs once right after this bean is built and its
 * dependencies are injected. Phase 3 replaces this with proper migrations.
 */
@Service
public class AuditService {

    public record AuditEntry(long id, String action, String subject, String detail, Instant createdAt) {
    }

    private static final RowMapper<AuditEntry> MAPPER = (rs, rowNum) -> new AuditEntry(
            rs.getLong("id"),
            rs.getString("audit_action"),
            rs.getString("audit_subject"),
            rs.getString("audit_detail"),
            rs.getTimestamp("created_at").toInstant());

    private final JdbcClient jdbc;
    private final Clock clock;

    public AuditService(DataSource dataSource, Clock clock) {
        this.jdbc = JdbcClient.create(dataSource);
        this.clock = clock;
    }

    @PostConstruct
    void createTable() {
        jdbc.sql("""
                create table if not exists audit_log (
                    id bigint generated by default as identity primary key,
                    audit_action varchar(60) not null,
                    audit_subject varchar(100) not null,
                    audit_detail varchar(500),
                    created_at timestamp not null
                )""").update();
    }

    @Transactional(propagation = Propagation.MANDATORY)
    public void recordWithinTransaction(String action, String subject, String detail) {
        insert(action, subject, detail);
    }

    @Transactional(propagation = Propagation.REQUIRES_NEW)
    public void recordIndependently(String action, String subject, String detail) {
        insert(action, subject, detail);
    }

    @Transactional(readOnly = true)
    public List<AuditEntry> findRecent(int limit) {
        return jdbc.sql("select id, audit_action, audit_subject, audit_detail, created_at "
                        + "from audit_log order by id desc limit ?")
                .param(limit)
                .query(MAPPER)
                .list();
    }

    @Transactional(readOnly = true)
    public List<AuditEntry> findBySubject(String subject) {
        return jdbc.sql("select id, audit_action, audit_subject, audit_detail, created_at "
                        + "from audit_log where audit_subject = ? order by id")
                .param(subject)
                .query(MAPPER)
                .list();
    }

    private void insert(String action, String subject, String detail) {
        jdbc.sql("insert into audit_log (audit_action, audit_subject, audit_detail, created_at) "
                        + "values (?, ?, ?, ?)")
                .params(action, subject, detail, Timestamp.from(clock.instant()))
                .update();
    }
}
